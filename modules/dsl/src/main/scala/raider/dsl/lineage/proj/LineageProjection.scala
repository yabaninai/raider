package raider.dsl.lineage.proj

/** Projection of a replayed lineage call-graph into an EXECUTABLE generated
  * Scala source string (LIN-02, ADR-027 + ADR-031). Per node the renderer emits
  * real composition over the projection runtime
  * (`raider.dsl.lineage.proj.runtime.LineageStep`): model and tool steps carry
  * the dataRef KEY (payloads stay in the lineage-data resource — `// data:`
  * comments only) and thread their dataflow inputs as VALUES through a
  * `flatMap` chain (in-scope dependency ids are bound report values, cross-
  * scope ids stay string literals); delegations and phases become named defs
  * building sub-`Program`s spliced pre-order; a recorded-failed node becomes
  * `LineageStep.failed` (typed short-circuit, ADR-031 §2.4). The generated file
  * is a dry-run description — it dispatches no provider call and no tool, at
  * construction and at execution — and is never a replay or rerun entrypoint
  * (the emitted header states this, ADR-031 §2.1 rule 1). Output is
  * byte-identical on repeat (LIN2-C-01): all mutable state (output buffer,
  * def-name counters, cycle path, bind-var counters) is local to the
  * invocation, so concurrent renders never interfere (LIN2-C-03).
  */
enum NodeKind:
  case ModelCall(model: String, round: Int)
  case ToolCall(tool: String, recovery: String)
  case Delegation(agent: String)
  case Phase(name: String)

final case class NodeView(
    id: String,
    kind: NodeKind,
    parentId: Option[String],
    children: Vector[NodeView],
    dataRef: Option[String],
    // ADR-031 §2.6: graph dataflow edges — ids of the nodes this node depends
    // on (mirrors DataNode.inputs on the frozen wire). Defaulted so every
    // existing construction site compiles unchanged; the view adapter
    // populates the field from the graph and the renderer threads the ids as
    // values into the generated steps (`LineageStep.inputs`).
    inputs: Vector[String] = Vector.empty,
    // ADR-031 §2.4/§2.5: the node's RECORDED OUTCOME CLASS as carried by the
    // graph (the lineage-data v1 vocabulary: "Succeeded" / "Failed" /
    // "Cancelled" / "Timeout"), None when the graph carries no outcome. This
    // is a GRAPH FIELD, not data-derived: the rendering layer's data source is
    // the graph model only (ADR-031 §2.1) — the renderer never reads
    // lineage-data.json. Defaulted so existing construction sites compile
    // unchanged. A recorded non-success class makes the renderer emit
    // `LineageStep.failed` with the bounded, payload-free reason phrase
    // "recorded outcome: <class>" (never a result tail or args — payloads stay
    // addressable by dataRef only, ADR-031 §2.5).
    outcome: Option[String] = None
)

trait LineageView:
  def runId: String
  def roots: Vector[NodeView]

enum RenderError:
  case UnknownKind(detail: String)
  case Empty
  case Cyclic(id: String)

object LineageRenderer:

  private val Header =
    "// Generated by Raider lineage projection (ADR-027). Do not edit — comparator detects edits."

  /** ADR-031 §2.1 rule 1: the generated source is NOT a rerun/replay entrypoint
    * and must say so.
    */
  private val DryRunStatement = Vector(
    "// ADR-031 dry-run description: executing this projection dispatches no model call, no",
    "// tool call, no I/O — it only reports the recorded call-graph structure. Not a replay",
    "// or rerun entrypoint."
  )

  private val Indent = "  "

  /** Recorded outcome classes that project to a failed step (ADR-031 §2.4):
    * every recorded non-success is an honest short-circuit. "Succeeded" and
    * None project to reporting steps; any other string is a future wire
    * revision and is typed-rejected (UnknownKind), never guessed.
    */
  private val FailedOutcomes = Set("Failed", "Cancelled", "Timeout")
  private val SuccessOutcome = "Succeeded"

  /** One planned emission of a scope body: either a def call (the object-level
    * def name applied to `()`) or a runtime step constructor with the inputs
    * slot left open for scope-local value binding at emission time.
    */
  private enum StepPlan:
    def nodeId: String
    def dataRef: Option[String]

    case Call(nodeId: String, dataRef: Option[String], call: String)
        extends StepPlan

    case Ctor(
        nodeId: String,
        dataRef: Option[String],
        inputs: Vector[String],
        prefix: String,
        suffix: String
    ) extends StepPlan

  private final case class DefBlock(
      name: String,
      body: scala.collection.mutable.ArrayBuffer[StepPlan]
  )

  /** Renders the view deterministically: roots and children are walked in
    * pre-order, so the output is byte-identical on repeat (LIN2-C-01).
    *
    * Typed failures: `Empty` for a rootless graph, `Cyclic` when a node id
    * repeats on the current root-to-node path, `UnknownKind` for a node kind or
    * a recorded outcome class this revision does not render (defensive against
    * future wire revisions).
    */
  def render(v: LineageView): Either[RenderError, String] =
    if v.roots.isEmpty then Left(RenderError.Empty)
    else
      val out = new StringBuilder
      val path = scala.collection.mutable.Set.empty[String]
      val defCounts = scala.collection.mutable.HashMap.empty[String, Int]
      val defs = scala.collection.mutable.ArrayBuffer.empty[DefBlock]

      def nextDefName(base: String): String =
        val seen = defCounts.getOrElse(base, 0)
        defCounts(base) = seen + 1
        if seen == 0 then base else base + "_" + (seen + 1)

      def dataSuffix(n: NodeView): String =
        // data refs enter a `//` comment too, so they pass through the same
        // escape discipline as quoted literals (W9 review F4).
        n.dataRef.fold("")(ref => " // data: " + escape(ref))

      def strLit(raw: String): String = "\"" + escape(raw) + "\""

      def refLit(dataRef: Option[String]): String =
        dataRef.fold("None")(ref => "Some(" + strLit(ref) + ")")

      /** The recorded failure class of a node, if any (ADR-031 §2.4). The
        * source is the GRAPH field [[NodeView.outcome]] — the rendering layer's
        * data source is the graph model only (ADR-031 §2.1); a data-derived
        * source is impossible without widening the render API.
        */
      def failureClass(n: NodeView): Either[RenderError, Option[String]] =
        n.outcome match
          case None | Some(SuccessOutcome)               => Right(None)
          case Some(cls) if FailedOutcomes.contains(cls) => Right(Some(cls))
          case Some(other) =>
            Left(
              RenderError.UnknownKind(
                "unsupported recorded outcome: " + escape(other)
              )
            )

      /** Plans one node step: the plain reporting constructor, or — for a
        * recorded non-success — the typed `LineageStep.failed` (short-circuit,
        * bounded payload-free reason phrase, ADR-031 §2.4/§2.5).
        */
      def atomicStep(
          n: NodeView,
          nesting: Int,
          plainPrefix: String,
          failedKindText: String
      ): Either[RenderError, StepPlan] =
        failureClass(n).map {
          case None =>
            StepPlan.Ctor(
              n.id,
              n.dataRef,
              n.inputs,
              plainPrefix + refLit(n.dataRef) + ", ",
              ", nesting = " + nesting + ")"
            )
          case Some(cls) =>
            StepPlan.Ctor(
              n.id,
              n.dataRef,
              n.inputs,
              "LineageStep.failed(" + strLit(n.id) + ", " + failedKindText +
                ", " + refLit(n.dataRef) + ", ",
              ", nesting = " + nesting + ", reason = " +
                strLit("recorded outcome: " + cls) + ")"
            )
        }

      /** Plans a named def (Delegation/Phase) at `depth`: registers the
        * object-level def block (own node step first, then children — the
        * pre-order body), and plans the parent-scope def call. The def's own
        * node step lives INSIDE the body (nesting = depth + 1, ADR-031 §2.3),
        * so a childless def still has one real statement and a recorded failure
        * short-circuits from within the sub-Program.
        */
      def namedDef(
          n: NodeView,
          depth: Int,
          base: String,
          label: String,
          failedKindText: String,
          into: scala.collection.mutable.ArrayBuffer[StepPlan]
      ): Either[RenderError, Unit] =
        val defName = nextDefName(base)
        // Reserve the def block BEFORE recursing: object-level defs are
        // emitted in PRE-ORDER discovery order (outer def first).
        val body = scala.collection.mutable.ArrayBuffer.empty[StepPlan]
        defs += DefBlock(defName, body)
        for
          own <- atomicStep(
            n,
            depth + 1,
            "LineageStep." + (if n.kind.isInstanceOf[NodeKind.Delegation] then
                                "delegation("
                              else "phase(") +
              strLit(n.id) + ", " + strLit(label) + ", ",
            failedKindText
          )
          _ = body += own
          _ <- n.children.foldLeft[Either[RenderError, Unit]](Right(()))(
            (acc, c) => acc.flatMap(_ => visit(c, depth + 1, body))
          )
          _ = into += StepPlan.Call(n.id, n.dataRef, defName + "(())")
        yield ()

      def visit(
          n: NodeView,
          depth: Int,
          into: scala.collection.mutable.ArrayBuffer[StepPlan]
      ): Either[RenderError, Unit] =
        if path.contains(n.id) then Left(RenderError.Cyclic(n.id))
        else
          path += n.id
          val kind: Matchable = n.kind
          val walkChildren
              : Either[RenderError, Unit] => Either[RenderError, Unit] =
            _.flatMap(_ =>
              n.children.foldLeft[Either[RenderError, Unit]](Right(()))(
                (acc, c) => acc.flatMap(_ => visit(c, depth, into))
              )
            )
          val planned: Either[RenderError, Unit] = kind match
            case NodeKind.ModelCall(model, round) =>
              walkChildren(
                atomicStep(
                  n,
                  depth,
                  "LineageStep.model(" + strLit(n.id) + ", " + strLit(model) +
                    ", " + round + ", ",
                  "NodeKind.ModelCall(" + strLit(model) + ", " + round + ")"
                ).map(into += _)
              )
            case NodeKind.ToolCall(tool, recovery) =>
              walkChildren(
                atomicStep(
                  n,
                  depth,
                  "LineageStep.tool(" + strLit(n.id) + ", " + strLit(tool) +
                    ", " + strLit(recovery) + ", ",
                  "NodeKind.ToolCall(" + strLit(tool) + ", " + strLit(
                    recovery
                  ) +
                    ")"
                ).map(into += _)
              )
            case NodeKind.Delegation(agent) =>
              // namedDef walks the children itself (they belong to the def
              // body scope, one level deeper).
              namedDef(
                n,
                depth,
                "delegation_" + slug(agent),
                agent,
                "NodeKind.Delegation(" + strLit(agent) + ")",
                into
              )
            case NodeKind.Phase(name) =>
              namedDef(
                n,
                depth,
                "phase_" + slug(name),
                name,
                "NodeKind.Phase(" + strLit(name) + ")",
                into
              )
            case other =>
              val describe =
                Option(other).fold("null")(_.getClass.getSimpleName)
              Left(
                RenderError.UnknownKind(
                  "unsupported node kind: " + describe
                )
              )
          planned.map(_ => path -= n.id)

      // ----- emission ---------------------------------------------------------

      def inputsArg(
          inputs: Vector[String],
          vars: scala.collection.mutable.HashMap[String, String]
      ): String =
        if inputs.isEmpty then "Vector.empty"
        else
          "Vector(" + inputs
            .map(id => vars.get(id).fold(strLit(id))(v => v + ".head.id"))
            .mkString(", ") + ")"

      def stepLine(
          s: StepPlan,
          vars: scala.collection.mutable.HashMap[String, String]
      ): String =
        val text = s match
          case StepPlan.Call(_, _, call) => call
          case StepPlan.Ctor(_, _, inputs, prefix, suffix) =>
            prefix + inputsArg(inputs, vars) + suffix
        text + s.dataRef.fold("")(ref => " // data: " + escape(ref))

      /** Emits one scope body as a value-threaded `flatMap` chain (ADR-031
        * §2.3): every step's report is bound (`n_<id>` variables, deduped per
        * scope) so a downstream step's `inputs` carry the bound ids of its
        * in-scope dependencies (`<var>.head.id` — pre-order vectors always
        * start with the own node); out-of-scope dependency ids stay string
        * literals. A single-step scope emits the bare expression. Each step
        * line keeps its `// data:` comment; the binding continues with a
        * leading-dot line so comments never split an expression.
        */
      def emitScope(steps: Vector[StepPlan], base: String): Unit =
        val vars = scala.collection.mutable.HashMap.empty[String, String]
        val varCounts = scala.collection.mutable.HashMap.empty[String, Int]
        def varFor(id: String): String =
          val baseName = "n_" + slug(id)
          val seen = varCounts.getOrElse(baseName, 0)
          varCounts(baseName) = seen + 1
          val name = if seen == 0 then baseName else baseName + "_" + (seen + 1)
          vars(id) = name
          name
        if steps.sizeIs == 1 then
          out.append(base).append(stepLine(steps.head, vars)).append('\n')
        else
          val last = steps.length - 1
          steps.zipWithIndex.foreach { (s, i) =>
            val ind = base + Indent * 2 * i
            out.append(ind).append(stepLine(s, vars)).append('\n')
            val v = varFor(s.nodeId)
            if i < last then
              out
                .append(ind + Indent)
                .append(".flatMap { ")
                .append(v)
                .append(" =>")
                .append('\n')
            else
              out
                .append(ind + Indent)
                .append(".map { ")
                .append(v)
                .append(" =>")
                .append('\n')
              out
                .append(ind + Indent * 2)
                .append(steps.map(s2 => vars(s2.nodeId)).mkString(" ++ "))
                .append('\n')
              out.append(ind + Indent).append('}').append('\n')
          }
          for j <- last - 1 to 0 by -1 do
            out.append(base + Indent * (2 * j + 1)).append('}').append('\n')

      def emitMember(name: String, body: Vector[StepPlan]): Unit =
        // The sub-Program member is a val (strict, pure construction — the
        // runtime dispatches nothing at build time), mirroring the
        // review-approved PRC-02 fixture shape: the parent scope splices the
        // sub-program by applying it — `<name>(())` is `Program.apply(())`.
        out
          .append(Indent)
          .append("val ")
          .append(name)
          .append(": Program[Unit, Vector[StepReport]] =")
          .append('\n')
        out
          .append(Indent * 2)
          .append("Program.fromFunction(\"")
          .append(name)
          .append("\") { _ =>")
          .append('\n')
        emitScope(body, Indent * 3)
        out.append(Indent * 2).append('}').append('\n')

      // ----- collect, then emit ----------------------------------------------

      val rootSteps = scala.collection.mutable.ArrayBuffer.empty[StepPlan]
      v.roots
        .foldLeft[Either[RenderError, Unit]](Right(()))((acc, r) =>
          acc.flatMap(_ => visit(r, 0, rootSteps))
        )
        .map { _ =>
          out.append(Header).append('\n')
          DryRunStatement.foreach(line => out.append(line).append('\n'))
          out.append('\n')
          out.append("import raider.core.Program").append('\n')
          out.append("import raider.dsl.lineage.proj.NodeKind").append('\n')
          out
            .append(
              "import raider.dsl.lineage.proj.runtime.{LineageStep, StepReport}"
            )
            .append('\n')
          out.append('\n')
          out
            .append("object lineage_")
            .append(slug(v.runId))
            .append(':')
            .append('\n')
          defs.zipWithIndex.foreach { (d, i) =>
            if i > 0 then out.append('\n')
            emitMember(d.name, d.body.toVector)
          }
          if defs.nonEmpty then out.append('\n')
          val objName = "lineage_" + slug(v.runId)
          out
            .append(Indent)
            .append("val program: Program[Unit, Vector[StepReport]] =")
            .append('\n')
          out
            .append(Indent * 2)
            .append("Program.fromFunction(\"")
            .append(objName)
            .append("\") { _ =>")
            .append('\n')
          emitScope(rootSteps.toVector, Indent * 3)
          out.append(Indent * 2).append('}').append('\n')
          out.toString
        }

  /** Identifier slug: letters/digits/underscore kept, everything else mapped to
    * `_`; an empty or digit-leading result is prefixed so it is a valid Scala
    * identifier. Deterministic.
    */
  private def slug(raw: String): String =
    val cleaned = raw.map(c => if c.isLetterOrDigit || c == '_' then c else '_')
    if cleaned.isEmpty || cleaned.head.isDigit then "_" + cleaned else cleaned

  /** Escape discipline for free text entering the generated source (W9 review
    * F4): besides the Scala-literal escapes `\` and `"`, control characters are
    * neutralized exactly like the canonical-form esc of the runtime GraphHash —
    * `\n`, `\r`, `\t` become the two-character sequences `\n`/`\r`/`\t`, and
    * every other C0 control (U+0000–U+001F) or DEL (U+007F) becomes `\xHH` (two
    * lowercase hex digits of the code point). A model/tool/recovery name or
    * data ref carrying raw newlines can therefore no longer split a `//`
    * comment or a string literal: every emitted line stays single-line, so the
    * generated artifact keeps its line structure regardless of hostile node
    * payloads. Deterministic and injective by construction: each `\` in the
    * output opens exactly one of the listed sequences, and no escaped text
    * contains a raw newline, quote or control character.
    */
  private def escape(raw: String): String =
    val out = new StringBuilder(raw.length + 8)
    raw.foreach {
      case '\\'                          => out.append("\\\\")
      case '"'                           => out.append("\\\"")
      case '\n'                          => out.append("\\n")
      case '\r'                          => out.append("\\r")
      case '\t'                          => out.append("\\t")
      case c if c < ' ' || c == '\u007f' => out.append(f"\\x${c.toInt}%02x")
      case c                             => out.append(c)
    }
    out.result()
